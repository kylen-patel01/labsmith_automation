    def compute_all(self):
        '''
        Preview the required pressure and dispense time for all experiments.

        Back-calculates pressure from the desired flow using the calibration equation
        (flow = slope * pressure + intercept) for each experiment's selected calibration.
        Dispense time is derived from volume / flow.
        Results are displayed in the GUI labels without running any hardware.

        Returns: None
        '''
        for i, r in enumerate(self.reservoirs):
            calib_name = r['calib_curve'].get()
            if not calib_name:
                messagebox.showerror('Error', f'Stage {i+1}: Select a calibration curve/solution')
                return

            try:
                clear_volume = float(r['clear_volume'].get())
                clear_flow = float(r['clear_flow'].get())
                clear_time = calculate_clear_stage(clear_volume, clear_flow)
                if clear_volume < 0:
                    raise ValueError('Clear volume must be non-negative.')
                if calib_name == 'Hold' and clear_volume > 0:
                    raise ValueError('Hold stages need a calibration curve to calculate clear pressure.')
                if calib_name == 'Hold':
                    clear_pressure = 0.0
                else:
                    info = self.curves[calib_name]
                    clear_pressure = calculate_target_pressure(
                        clear_flow, info.get('slope'), info.get('intercept'))
            except Exception as exc:
                messagebox.showerror('Error', f'Clear stage {i+1}: Invalid settings: {exc}')
                return
            r['clear_status_var'].set(
                f'Clears dead volume in {clear_time:.2f} s at {clear_pressure:.3f} kPa '
                f'({clear_flow:.2f} uL/min)')

            if calib_name == 'Hold':
                hold_time_value = 0.0
                try:
                    hold_time_value = float(r['hold_time'].get()) if not self.thermal_enabled_var.get() else 0.0
                except Exception:
                    messagebox.showerror('Error', f'Invalid hold time for stage {i+1}')
                    return
                r['pressure_lbl'].set('Pressure Target: N/A')
                r['time_lbl'].set(f'Hold Time: {hold_time_value:.2f} s')
                continue

            info      = self.curves[calib_name]
            slope     = info.get('slope')
            intercept = info.get('intercept')

            try:
                desired_flow = float(r['flow'].get())
                vol = float(r['vol'].get())
            except Exception:
                messagebox.showerror('Error', f'Invalid inputs for stage {i+1}')
                return

            pressure  = (desired_flow - intercept) / slope if slope != 0 else None
            disp_time = (vol / desired_flow) * 60.0         if desired_flow > 0 else None

            r['pressure_lbl'].set(f'Pressure Target: {pressure:.3f} kPa' if pressure  is not None else 'Pressure Target: N/A')
            r['time_lbl'].set(    f'Dispense Time: {disp_time:.2f} s'     if disp_time is not None else 'Time (s): N/A')

        status = 'Computed values for all reservoirs'
        if self.thermal_enabled_var.get():
            status += ' | Thermal control enabled'
        self.status_var.set(status)

    def state_label_from_file(self, state_file):
        """
        Read the per-stage state file and return a human label for the latest integer state.
        State file format: time_s;state (one row per event). Returns None if unavailable.
        """
        labels = {
            0: 'Idle/starting',
            1: 'Heating to target',
            2: 'Temperature dwell',
            3: 'Hold (no temp)',
            4: 'Initializing valves',
            5: 'Depressurizing',
            6: 'Dumping air / retrying',
            7: 'Refilling syringe',
            8: 'Pressurizing',
            9: 'Stabilizing pressure',
            10: 'Injecting',
            11: 'Closing / shutdown',
            12: 'Completed stage'
        }
        if not state_file or not os.path.exists(state_file):
            return None
        try:
            with open(state_file, 'r') as f:
                lines = [l.strip() for l in f if l.strip()]
            if not lines:
                return None
            # skip header if present
            if lines[0].lower().startswith('time'):
                lines = lines[1:]
            if not lines:
                return None
            # Attempt to detect the system_state column by header name.
            header = [p.strip().strip('"').lower() for p in lines[0].replace(',', ';').split(';') if p.strip()]
            if 'system_state' in header:
                state_index = header.index('system_state')
            elif len(header) >= 3:
                state_index = 2
            else:
                state_index = 1

            last = lines[-1]
            parts = [p.strip().strip('"') for p in last.replace(',', ';').split(';')]
            if len(parts) <= state_index:
                return None
            state_field = parts[state_index]
            try:
                state_int = int(float(state_field))
            except Exception:
                return None
            return labels.get(state_int, f'State {state_int}')
        except Exception:
            return None

    def pause_experiment(self):
        '''
        Pause the currently running experiment.
        
        When paused, the uProcess hardware holds the current state and CSV data
        collection is suspended. Use resume_experiment to continue from this point.

        Returns: None
        '''
        if self.pipe is not None and self.is_running:
            try:
                uProcess.Pause(self.pipe)
                self.is_paused = True
                self.status_var.set('Experiment paused')
                self.pause_btn.configure(state='disabled')
                self.resume_btn.configure(state='normal')
                self.stop_btn.configure(state='normal')
            except Exception as e:
                messagebox.showerror('Error', f'Failed to pause experiment: {e}')

    def resume_experiment(self):
        '''
        Resume a paused experiment.
        
        Resumes the paused experiment from where it was paused. CSV data collection
        will continue to populate the same file without interruption.

        Returns: None
        '''
        if self.pipe is not None and self.is_paused:
            try:
                uProcess.Pause(self.pipe)
                self.is_paused = False
                self.status_var.set('Experiment resumed')
                self.pause_btn.configure(state='normal')
                self.resume_btn.configure(state='disabled')
            except Exception as e:
                messagebox.showerror('Error', f'Failed to resume experiment: {e}')

    def stop_experiment(self):
        '''
        Stop the currently running experiment and save all data.
        
        Stops the hardware and gracefully terminates the experiment. All CSV data
        collected so far is saved to the output folder. The stop can be initiated
        from either running or paused states.

        Returns: None
        '''
        if self.pipe is not None:
            try:
                uProcess.Stop(self.pipe)
                self.stop_requested = True
                self.status_var.set('Experiment stopping...')
                self.pause_btn.configure(state='disabled')
                self.resume_btn.configure(state='disabled')
                self.stop_btn.configure(state='disabled')
            except Exception as e:
                messagebox.showerror('Error', f'Failed to stop experiment: {e}')

    def run_experiment(self):
        '''
        Run all configured experiments sequentially through uProcess.

        For each experiment:
        - Validates inputs and uses the experiment's selected calibration curve
        - Computes required pressure and dispense time
        - Builds the uProcess script (with optional thermal parameters)
        - Sends the script to hardware and waits for completion
        - Saves per-run flow/pressure plots (and temperature plots if enabled)

        After all runs:
        - Computes steady-state flow averages and compares to desired values
        - Warns if any experiment exceeds the deviation threshold
        - Concatenates all CSVs into a single file with a continuous time axis
        - Saves combined overlay and temperature plots

        Returns: None
        '''
        timestamp = time.strftime('%Y%m%d_%H%M%S')
        exp_name  = self.output_label.get().strip() or timestamp
        save_output = self.save_output_var.get()
        temp_output_root = None

        if not save_output:
            temp_output_root = tempfile.mkdtemp(prefix='demo_output_', dir=BASE_DIR)

        use_thermal = self.thermal_enabled_var.get()

        self.reset_stage_statuses('Waiting for start')
        self.write_live_state(done=False)
        self.start_live_plotter()

        # Validate all inputs up front before opening the hardware pipe
        run_params      = []
        execution_params = []
        individual_csvs = []
        calib_names     = []  # Track calibration names for output organization

        for i, r in enumerate(self.reservoirs):
            calib_name = r['calib_curve'].get()
            if not calib_name:
                messagebox.showerror('Error', f'Stage {i+1}: Select a calibration curve or Hold')
                return

            hold_mode = calib_name == 'Hold'
            temp_lower = temp_upper = temp_dwell = temp_ramp = None
            if use_thermal:
                try:
                    temp_lower = float(r['temp_lower'].get())
                    temp_upper = float(r['temp_upper'].get())
                    temp_dwell = float(r['temp_dwell'].get())
                    temp_ramp  = float(r['temp_ramp'].get())
                except Exception:
                    messagebox.showerror('Error', f'Invalid thermal parameters for stage {i+1}')
                    return

            threshold_pct_stage = 0.0
            try:
                pos_raw = str(r['pos'].get()).strip()
                pos = int(pos_raw) if pos_raw.isdigit() else min(8, 2 + i)
                if not hold_mode:
                    threshold_pct_stage = float(r['threshold'].get())
            except Exception:
                pos = min(8, 2 + i)
                if not hold_mode:
                    threshold_pct_stage = 10.0

            if not (2 <= pos <= 8):
                pos = max(2, min(8, pos))

            if hold_mode:
                try:
                    hold_time_s = float(r['hold_time'].get()) if not use_thermal else float(temp_dwell)
                except Exception:
                    messagebox.showerror('Error', f'Invalid hold time for stage {i+1}')
                    return
                desired_flow = 0.0
                vol = 0.0
                p_tol = 0.0
                pressure = 0.0
                disp_time = 0.0
            else:
                try:
                    desired_flow = float(r['flow'].get())
                    vol          = float(r['vol'].get())
                    p_tol        = float(r['p_tol'].get())
                except Exception:
                    messagebox.showerror('Error', f'Invalid inputs for stage {i+1}')
                    return
                info      = self.curves[calib_name]
                slope     = info.get('slope')
                intercept = info.get('intercept')
                pressure  = (desired_flow - intercept) / slope if slope != 0 else 0.0
                disp_time = (vol / desired_flow) * 60.0         if desired_flow > 0 else 0.0

            try:
                clear_volume = float(r['clear_volume'].get())
                clear_flow = float(r['clear_flow'].get())
                clear_time = calculate_clear_stage(clear_volume, clear_flow)
                if clear_volume < 0:
                    raise ValueError('Clear volume must be non-negative.')
                if hold_mode and clear_volume > 0:
                    raise ValueError('Hold stages need a calibration curve to calculate clear pressure.')
                if hold_mode:
                    clear_pressure = 0.0
                else:
                    clear_pressure = calculate_target_pressure(
                        clear_flow, slope, intercept)
            except Exception as exc:
                messagebox.showerror('Error', f'Clear stage {i+1}: Invalid settings: {exc}')
                return
            
            # Create output directory using the project name as the top-level folder.
            # In demo mode, send outputs to a temporary folder so no persistent files are left behind.
            out_dir = os.path.join(BASE_DIR, 'ExperimentData', exp_name)
            if not save_output:
                out_dir = temp_output_root
            os.makedirs(out_dir, exist_ok=True)
            
            # Construct filename: projectname_Res#_Run#_(optional timestamp).csv
            include_ts = self.include_timestamp_var.get()
            base_name = f'{exp_name}_Stage{i+1}_Res{pos}'
            
            if include_ts:
                out_csv = os.path.join(out_dir, f'{base_name}_{timestamp}.csv').replace('\\', '/')
            else:
                out_csv = os.path.join(out_dir, f'{base_name}.csv').replace('\\', '/')

            # Per-stage state file path (will be written by the uProcess script)
            state_file = os.path.join(out_dir, f'{base_name}_state.csv').replace('\\', '/')
            try:
                # create file with header so GUI can tail it immediately
                with open(state_file, 'w') as sf:
                    sf.write('time_s;state\n')
            except Exception:
                pass

            if hold_mode:
                r['pressure_lbl'].set('Pressure: N/A')
                if use_thermal:
                    r['time_lbl'].set(f'Hold Time (s): {hold_time_s:.2f}')
                else:
                    r['time_lbl'].set(f'Hold Time (s): {hold_time_s:.2f}')
            else:
                r['pressure_lbl'].set(f'Pressure: {pressure:.3f} kPa' if slope != 0 else 'Pressure: N/A')
                r['time_lbl'].set(f'Time (s): {disp_time:.2f}')

            stage_param = {
                'desired_flow': desired_flow, 'disp_time': disp_time, 'pos': pos,
                'p_tol': p_tol, 'pressure': pressure, 'out_csv': out_csv,
                'temp_lower': temp_lower, 'temp_upper': temp_upper,
                'temp_dwell': temp_dwell, 'temp_ramp': temp_ramp,
                'hold_mode': hold_mode, 'hold_time': hold_time_s if hold_mode else 0.0,
                'threshold_pct': threshold_pct_stage,
                'out_dir': out_dir,
                'state_file': state_file,
                'stage_index': i, 'is_clear': False,
            }
            run_params.append(stage_param)

            if clear_volume > 0:
                clear_base = f'{exp_name}_ClearBeforeStage{i+1}_Res{pos}'
                if include_ts:
                    clear_csv = os.path.join(out_dir, f'{clear_base}_{timestamp}.csv').replace('\\', '/')
                else:
                    clear_csv = os.path.join(out_dir, f'{clear_base}.csv').replace('\\', '/')
                clear_state = os.path.join(out_dir, f'{clear_base}_state.csv').replace('\\', '/')
                try:
                    with open(clear_state, 'w') as sf:
                        sf.write('time_s;state\n')
                except Exception:
                    pass

                clear_param = {
                    'desired_flow': clear_flow, 'disp_time': clear_time, 'pos': pos,
                    'p_tol': p_tol, 'pressure': clear_pressure, 'out_csv': clear_csv,
                    'temp_lower': None, 'temp_upper': None,
                    'temp_dwell': None, 'temp_ramp': None,
                    'hold_mode': False, 'hold_time': 0.0, 'threshold_pct': 0.0,
                    'out_dir': out_dir, 'state_file': clear_state,
                    'stage_index': i, 'is_clear': True,
                }
                execution_params.append(clear_param)
            execution_params.append(stage_param)
            calib_names.append(calib_name)

        # Open a single hardware pipe shared across all runs
        try:
            self.pipe = uProcess.OpenCommandPipe()
        except Exception as e:
            messagebox.showerror('Error', f'Could not open uProcess pipe: {e}')
            return

        # Set initial state and enable control buttons
        self.is_running = True
        self.is_paused = False
        self.stop_requested = False
        self.run_btn.configure(state='disabled')
        self.pause_btn.configure(state='normal')
        self.resume_btn.configure(state='disabled')
        self.stop_btn.configure(state='normal')

        for i, p in enumerate(execution_params):
            stage_index = p.get('stage_index', i)
            status_index = stage_index
            # Check if user requested stop
            if self.stop_requested:
                self.status_var.set('Experiment stopped by user')
                break

            # Mark this stage as running and ensure others are queued
            try:
                # Set all remaining stages to Queued if they are still at the default
                for q in range(len(self.reservoirs)):
                    try:
                        if q < stage_index:
                            # previous stages remain as-is (may have been updated by state file)
                            continue
                        self.set_stage_status(q, 'Queued')
                    except Exception:
                        pass
                if p.get('is_clear'):
                    self.set_clear_stage_status(status_index, 'Clearing dead volume')
                else:
                    self.set_stage_status(status_index, f'Running stage {status_index+1}')
            except Exception:
                pass

            self.write_live_state(csv_path=p['out_csv'], run_index=i)

            script_text = build_script(
                p['pressure'], int(round(p['disp_time'])), p['out_csv'],
                p_tol=p['p_tol'], position=p['pos'], use_thermal=use_thermal and not p.get('is_clear'),
                temp_lower=p['temp_lower'], temp_upper=p['temp_upper'],
                temp_dwell=p['temp_dwell'], temp_ramp=p['temp_ramp'],
                hold_mode=p['hold_mode'], hold_time_s=p['hold_time'],
                state_output_file=p.get('state_file')
            )
            script_text = script_text.replace('\x00', '').replace('\n', '\r\n')

            try:
                run_label = f"clear before Stage {status_index+1}" if p.get('is_clear') else f"stage {status_index+1}"
                self.status_var.set(f"Running {run_label} at reservoir valve # {p['pos']}…")
                self.root.update()
                uProcess.SetScript(self.pipe, script_text)
                uProcess.Run(self.pipe)
                
                # Monitor the running experiment, handle pause/resume/stop
                while uProcess.IsRunning(self.pipe) and not self.stop_requested:
                    # Handle pause state
                    while self.is_paused and not self.stop_requested:
                        self.status_var.set(f"Experiment {i+1} paused at valve position {p['pos']}")
                        time.sleep(0.5)
                        self.root.update()
                    
                    # If stop was requested while paused, exit
                    if self.stop_requested:
                        break
                    
                    # Check if still running
                    if not uProcess.IsRunning(self.pipe):
                        break
                    
                    time.sleep(0.5)
                    self.root.update()
                    # Tail the state file (if present) and update stage status
                    try:
                        state_file_path = p.get('state_file')
                        label = self.state_label_from_file(state_file_path)
                        if label:
                            if not p.get('is_clear'):
                                self.set_stage_status(status_index, label)
                    except Exception:
                        pass
                
                # If stop was requested, halt the experiment
                if self.stop_requested:
                    try:
                        uProcess.Stop(self.pipe)
                    except Exception:
                        pass
                    # mark current stage as stopped
                    try:
                        if p.get('is_clear'):
                            self.set_clear_stage_status(status_index, 'Stopped')
                        else:
                            self.set_stage_status(status_index, 'Stopped')
                    except Exception:
                        pass
                    break
                    
            except Exception as e:
                messagebox.showerror('Error', f'Run failed for {run_label}: {e}')
                break

            individual_csvs.append(p['out_csv'])

            # On normal completion, set a final status from the state file or 'Completed'
            try:
                final_label = self.state_label_from_file(p.get('state_file'))
                if not final_label:
                    final_label = 'Completed'
                if p.get('is_clear'):
                    self.set_clear_stage_status(status_index, f'Clear stage: {final_label}')
                else:
                    self.set_stage_status(status_index, final_label)
            except Exception:
                try:
                    if p.get('is_clear'):
                        self.set_clear_stage_status(status_index, 'Clear stage: Completed')
                    else:
                        self.set_stage_status(status_index, 'Completed')
                except Exception:
                    pass

            # Per-run plots (flow/pressure overlay and optional temperature)
            try:
                tcol, fcol, df = extract_flow(p['out_csv'])
                if tcol and fcol:
                    pressure_col = next((c for c in df.columns
                                         if any(k in c.lower() for k in ('press', 'kpa'))), None)
                    plot_overlay(df, tcol, fcol, pressure_col,
                                 p['out_csv'].replace('.csv', '.png'),
                                 title=f'Res{i+1} trace')
                    if use_thermal:
                        temp_col = next((c for c in df.columns
                                          if 'T00389' in c or ('temp' in c.lower() and '(c)' in c.lower())), None)
                        if temp_col:
                            plot_temperature(df, tcol, temp_col,
                                             p['out_csv'].replace('.csv', '_temperature.png'),
                                             title=f'Res{i+1} temperature')
            except Exception:
                pass

        try:
            uProcess.CloseCommandPipe(self.pipe)
        except Exception:
            pass

        # Reset state variables and button states
        self.is_running = False
        self.is_paused = False
        self.stop_requested = False
        self.pipe = None
        self.run_btn.configure(state='normal')
        self.pause_btn.configure(state='disabled')
        self.resume_btn.configure(state='disabled')
        self.stop_btn.configure(state='disabled')

        self.write_live_state(done=True)

        # Steady-state flow analysis and results collection
        results = []
        exceeded = []
        for idx, p in enumerate(run_params):
            if p['hold_mode']:
                self.result_vars[idx].set(f'Stage {idx+1} Hold Time: {p["hold_time"]:.2f} s')
                results.append({'avg_flow': None, 'dev_pct': None, 'desired_flow': p['desired_flow'], 'hold_time': p['hold_time']})
                continue
            try:
                tcol, fcol, dfi = extract_flow(p['out_csv'])
                avg, std = compute_steady_stats_from_dispense(dfi, tcol, fcol, p['disp_time'], p['pos'])
            except Exception:
                avg = None
                std = None

            dev = None
            if avg is None:
                self.result_vars[idx].set(f'Stage {idx+1} Avg: N/A')
            else:
                dev = abs(avg - p['desired_flow']) / p['desired_flow'] * 100.0
                self.result_vars[idx].set(f'Stage {idx+1} Avg: {avg:.2f} uL/min (std: {std:.2f} uL/min; dev: {dev:.1f}%)')
                if dev > p['threshold_pct']:
                    exceeded.append((idx+1, avg, dev))
            
            results.append({'avg_flow': avg, 'dev_pct': dev, 'desired_flow': p['desired_flow'], 'hold_time': None, 'std_flow': std})

        if exceeded:
            msgs = [f'Stage {r} avg {a:.1f} uL/min deviates {d:.1f}%' for r, a, d in exceeded]
            messagebox.showwarning('Threshold Exceeded',
                                   'Some stages exceed the desired threshold:\n' + '\n'.join(msgs))

        # Save experiment summary and combined outputs only when the user wants persistent data.
        if save_output:
            summary_threshold = max((p['threshold_pct'] for p in run_params if p.get('threshold_pct') is not None), default=10.0)
            self._save_experiment_summary(run_params, results, exp_name, timestamp, use_thermal, summary_threshold)

            # Combine all CSVs into one file with a continuous time axis
            if individual_csvs:
                self._combine_and_save(individual_csvs, run_params, exp_name, timestamp, use_thermal)
        else:
            self.status_var.set('Demo run complete. Temporary output files were not saved.')

        if temp_output_root and not save_output:
            try:
                shutil.rmtree(temp_output_root, ignore_errors=True)
            except Exception:
                pass

    def _save_experiment_summary(self, run_params, results, exp_name, timestamp, use_thermal, threshold_pct):
        '''
        Save a text summary of the experiment parameters and results.
        
        Creates a .txt file in the first experiment's output directory containing:
        - Experiment metadata (name, date/time, settings)
        - Per-experiment parameters (calibration, valve position, flow, volume, etc.)
        - Per-experiment results (steady-state flow, deviation from desired)
        - Summary statistics and threshold violations

        Parameters:
        - run_params:   list of run parameter dicts with all experimental settings
        - results:      list of result dicts with avg_flow, dev_pct, desired_flow
        - exp_name:     experiment name/project name
        - timestamp:    run timestamp string
        - use_thermal:  whether thermal control was enabled
        - threshold_pct: deviation threshold percentage

        Returns: None
        '''
        if not run_params:
            return
        
        # Save in the first experiment's output directory
        out_dir = run_params[0]['out_dir']
        summary_file = os.path.join(out_dir, f'{exp_name}_summary.txt')
        
        try:
            with open(summary_file, 'w') as f:
                # Header
                f.write('=' * 80 + '\n')
                f.write('PROJECT SUMMARY\n')
                f.write('=' * 80 + '\n\n')
                
                # Experiment metadata
                f.write('PROJECT DATA SUMMARY\n')
                f.write('-' * 80 + '\n')
                f.write(f'Project Name:           {exp_name}\n')
                f.write(f'Timestamp:              {timestamp}\n')
                f.write(f'Thermal Control:        {"Enabled" if use_thermal else "Disabled"}\n')
                f.write(f'Deviation Threshold:    {threshold_pct}%\n')
                f.write(f'Number of Stages:  {len(run_params)}\n')
                f.write('\n')
                
                # Per-experiment parameters and results
                f.write('STAGE DETAILS\n')
                f.write('-' * 80 + '\n\n')
                
                for i, (p, r) in enumerate(zip(run_params, results)):
                    f.write(f'Stage {i+1}\n')
                    f.write('  Parameters:\n')
                    f.write(f'    Calibration Curve:    {os.path.basename(p["out_dir"]) if "out_dir" in p else "N/A"}\n')
                    f.write(f'    Valve Position:       {p["pos"]}\n')
                    f.write(f'    Desired Flow:         {p["desired_flow"]:.2f} µL/min\n')
                    f.write(f'    Dispense Volume:      {p["desired_flow"] * p["disp_time"] / 60:.2f} µL\n')
                    f.write(f'    Target Pressure:      {p["pressure"]:.3f} kPa\n')
                    f.write(f'    Pressure Tolerance:   {p["p_tol"]:.3f} kPa\n')
                    f.write(f'    Dispense Time:        {p["disp_time"]:.2f} s\n')
                    
                    if use_thermal:
                        f.write(f'    Temp Lower Bound:     {p.get("temp_lower", "N/A")} °C\n')
                        f.write(f'    Temp Upper Bound:     {p.get("temp_upper", "N/A")} °C\n')
                        f.write(f'    Thermal Dwell Time:   {p.get("temp_dwell", "N/A")} s\n')
                        f.write(f'    Temperature Ramp:     {p.get("temp_ramp", "N/A")} V/s\n')
                    
                    f.write('  Results:\n')
                    if p['hold_mode']:
                        f.write(f'    Hold Time:            {p["hold_time"]:.2f} s\n')
                        f.write(f'    Steady-State Flow:    N/A\n')
                        f.write(f'    Steady-State Std Dev: N/A\n')
                        f.write(f'    Deviation:            N/A\n')
                    elif r['avg_flow'] is None:
                        f.write(f'    Steady-State Flow:    N/A\n')
                        f.write(f'    Steady-State Std Dev: N/A\n')
                        f.write(f'    Deviation:            N/A\n')
                    else:
                        f.write(f'    Steady-State Flow:    {r["avg_flow"]:.2f} µL/min\n')
                        f.write(f'    Steady-State Std Dev: {r["std_flow"]:.2f} µL/min\n')
                        f.write(f'    Deviation:            {r["dev_pct"]:.2f}% from desired flow rate\n')
                    
                    csv_path = p.get('out_csv', 'N/A')
                    f.write(f'    Output CSV:           {os.path.basename(csv_path)}\n')
                    f.write('\n')
                
                # Summary statistics
                f.write('SUMMARY STATISTICS\n')
                f.write('-' * 80 + '\n')
                
                valid_flows = [r['avg_flow'] for r in results if r['avg_flow'] is not None]
                valid_stds = [r['std_flow'] for r in results if r['std_flow'] is not None]
                valid_devs = [r['dev_pct'] for r in results if r['dev_pct'] is not None]
                
                if valid_flows:
                    f.write(f'Average Steady-State Flow:  {np.mean(valid_flows):.2f} µL/min\n')
                    f.write(f'Min Steady-State Flow:      {np.min(valid_flows):.2f} µL/min\n')
                    f.write(f'Max Steady-State Flow:      {np.max(valid_flows):.2f} µL/min\n')

                if valid_stds:
                    f.write(f'Average Steady-State Std Dev: {np.mean(valid_stds):.2f} µL/min\n')
                    f.write(f'Min Steady-State Std Dev:     {np.min(valid_stds):.2f} µL/min\n')
                    f.write(f'Max Steady-State Std Dev:     {np.max(valid_stds):.2f} µL/min\n')
                
                if valid_devs:
                    exceeded_count = sum(1 for d in valid_devs if d > threshold_pct)
                    f.write(f'Stages Exceeding Desired Flow Threshold: {exceeded_count}/{len(results)}\n')
                
                f.write('\n' + '=' * 80 + '\n')
                
        except Exception as e:
            print(f'Error saving experiment summary: {e}')

    def _combine_and_save(self, csv_paths, run_params, exp_name, timestamp, use_thermal):
        '''
        Concatenate individual run CSVs into one file with a continuous time axis.
        Saves combined flow/pressure and (if enabled) temperature overlay plots.

        Since experiments may use different calibration curves, save combined files
        in each experiment's respective output directory.

        Parameters:
        - csv_paths:   list of paths to individual run CSV files
        - run_params:  list of run parameter dicts containing out_dir for each run
        - exp_name:    experiment name (used in the filename)
        - timestamp:   run timestamp string (used in the filename)
        - use_thermal: whether to also save a combined temperature plot

        Returns: None
        '''
        # Save combined file in the first experiment's directory (or combine all)
        if not run_params:
            return
        
        out_dir = run_params[0]['out_dir']
        combined_path = os.path.join(out_dir, f'{exp_name}_{timestamp}_combined.csv')
        
        try:
            dfs, offset, time_col_name = [], 0.0, None

            for fpath in csv_paths:
                try:
                    dfi = pd.read_csv(fpath, sep=';', skiprows=[0])
                except Exception:
                    dfi = pd.read_csv(fpath, sep=',')

                # Standardize the time column to numeric seconds and apply cumulative offset
                tcols = [c for c in dfi.columns if 'time' in c.lower()]
                if tcols:
                    tcol = tcols[0]
                    num  = pd.to_numeric(dfi[tcol].astype(str), errors='coerce')
                    if not num.isna().all():
                        dfi[tcol] = num
                    else:
                        parsed = pd.to_datetime(dfi[tcol].astype(str), errors='coerce')
                        if parsed.notna().any():
                            dfi[tcol] = (parsed - parsed.iloc[0]).dt.total_seconds()
                    dfi[tcol] = pd.to_numeric(dfi[tcol], errors='coerce')
                    dfi = dfi.dropna(subset=[tcol])
                    if not dfi.empty:
                        dfi[tcol]         = dfi[tcol] - dfi[tcol].min() + offset
                        dfi['Total_Time'] = dfi[tcol]
                        offset            = float(dfi[tcol].max())
                    if time_col_name and tcol != time_col_name:
                        dfi = dfi.rename(columns={tcol: time_col_name})
                    elif time_col_name is None:
                        time_col_name = tcol
                dfs.append(dfi)

            combined = pd.concat(dfs, ignore_index=True, sort=False)
            combined.to_csv(combined_path, index=False)

            # Detect columns for combined plots
            time_col     = next((c for c in combined.columns if 'time'  in c.lower()), None)
            flow_col     = next((c for c in combined.columns if 'sf'    in c.lower() or 'flow' in c.lower()), None)
            pressure_col = next((c for c in combined.columns if any(k in c.lower() for k in ('press', 'kpa'))), None)

            if time_col and flow_col:
                plot_overlay(combined, time_col, flow_col, pressure_col,
                             combined_path.replace('.csv', '_overlay.png'),
                             title='Combined Flow & Pressure')

            if use_thermal:
                temp_col = next((c for c in combined.columns
                                  if 'T00389' in c or ('temp' in c.lower() and '(c)' in c.lower())), None)
                if temp_col and time_col:
                    plot_temperature(combined, time_col, temp_col,
                                     combined_path.replace('.csv', '_temperature.png'),
                                     title='Combined Temperature')

            messagebox.showinfo('Done', f'Experiment complete. Combined file: {combined_path}')
            self.status_var.set('Done')

        except Exception as e:
            messagebox.showwarning('Warning', f'Could not combine CSVs: {e}')
            self.status_var.set('Done with warnings')

    def write_live_state(self, csv_path=None, run_index=0, done=False):
        '''
        Write a JSON file that tells the external live plotter which CSV is currently active.
        The live plotter polls this file and updates its display in real time.

        Parameters:
        - csv_path:  path to the CSV currently being written (None when idle or done)
        - run_index: index of the current run (0-based)
        - done:      True when the full experiment sequence has finished

        Returns: None
        '''
        try:
            with open(self.live_state_file, 'w') as f:
                json.dump({'csv_path': csv_path, 'run_index': run_index, 'done': done}, f)
        except Exception as e:
            print(f'write_live_state error: {e}')

    def start_live_plotter(self):
        '''
        Launch live_plotter_multi.py as a subprocess, if it is not already running.
        The live plotter reads live_state.json to know which CSV file to display.

        Returns: None
        '''
        try:
            if self.plot_proc is not None and self.plot_proc.poll() is None:
                return
            self.plot_proc = subprocess.Popen(
                [sys.executable, os.path.join(BASE_DIR, 'live_plotter_multi.py'), self.live_state_file]
            )
        except Exception as e:
            print(f'Could not start live plotter: {e}')

    def on_close(self):
        '''
        Cleanly shut down the live plotter and close the application window.

        Marks the live state as done, terminates the plotter subprocess if running,
        then destroys the Tkinter root window.

        Returns: None
        '''
        try:
            self.write_live_state(done=True)
            if self.plot_proc is not None and self.plot_proc.poll() is None:
                self.plot_proc.terminate()
        except Exception:
            pass
        self.root.destroy()

