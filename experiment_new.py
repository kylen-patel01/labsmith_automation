# Calibration Loading 

def find_calibration_curves(calib_root):
    '''
    Scan the calibration folder and build a dictionary of available calibrations.
    Each calibration lives in its own subfolder and must contain:
    - calibration_coeffs.txt  —  slope, intercept, and R2 values
    - calibration_curve.csv   —  raw data points for plotting
    - a .png image            —  pre-made calibration plot

    These files are generated by the calibration.py script. 

    Parameters:
    - calib_root: path to the root folder containing calibration subfolders

    Returns:
    A dict keyed by subfolder name. Each value is a dict with keys:
    slope, intercept, r2, dir, curve_csv, curve_png
    '''
    curves = {}
    if not os.path.isdir(calib_root):
        return curves

    for entry in sorted(os.listdir(calib_root)):
        full = os.path.join(calib_root, entry)
        if not os.path.isdir(full):
            continue

        vals = {'slope': None, 'intercept': None, 'r2': None,
                'dir': full, 'curve_csv': None, 'curve_png': None}

        for f in os.listdir(full):
            fl = f.lower()
            fp = os.path.join(full, f)
            if fl.startswith('calibration_coeffs') and fl.endswith('.txt'):
                vals.update(parse_coeffs_file(fp))
            elif fl.startswith('calibration_curve') and fl.endswith('.csv'):
                vals['curve_csv'] = fp
            elif fl.endswith('.png') and any(k in fl for k in ('plot', 'calib')):
                vals['curve_png'] = fp

        curves[entry] = vals

    return curves


def parse_coeffs_file(path):
    '''
    Read a calibration_coeffs.txt file and extract slope, intercept, and r2.

    Expected file format:
        Slope = <value>
        Intercept = <value>
        R2 = <value>

    Parameters:
    - path: full path to the coefficients text file

    Returns:
    A dict with keys slope, intercept, r2 (missing values remain None)
    '''
    vals = {'slope': None, 'intercept': None, 'r2': None}
    try:
        with open(path, 'r') as f:
            for line in f:
                line = line.strip()
                if line.lower().startswith('slope'):
                    vals['slope'] = float(line.split('=')[1])
                elif line.lower().startswith('intercept'):
                    vals['intercept'] = float(line.split('=')[1])
                elif line.lower().startswith('r2'):
                    try:
                        vals['r2'] = float(line.split('=')[1])
                    except Exception:
                        vals['r2'] = None
    except Exception:
        pass
    return vals

# uProcess Script Builder 

def build_script(target_pressure, dispense_time_s, trial_csv, p_tol, position=None,
                 use_thermal=False, temp_lower=None, temp_upper=None, temp_dwell=None, temp_ramp=None):
    '''
    Build the full script text that will be sent to uProcess.

    The script is composed of two parts:
    1. A parameter header generated by Python for this specific run
    2. The base .usq script file containing the hardware control logic

    Parameters:
    - target_pressure:  pressure to apply (kPa)
    - dispense_time_s:  duration to hold pressure (seconds)
    - trial_csv:        path where the output CSV will be saved
    - p_tol:            pressure tolerance (kPa), set per experiment in the GUI
    - position:         reservoir position on the AV801 selector valve
    - use_thermal:      whether to enable thermal control (True/False)
    - temp_lower:       lower temperature bound (C)
    - temp_upper:       upper temperature bound (C)
    - temp_dwell:       thermal stabilization dwell time (s)
    - temp_ramp:        temperature ramp rate (V/s)

    Returns:
    The complete script string ready to send to uProcess
    '''
    header = (
        f' ;Parameters \r\n'
        f'p_target = {target_pressure} kPa\r\n'
        f'p_tol = {p_tol} kPa\r\n'
        f'dispense_time = {dispense_time_s} s\r\n'
        f'output_file = "{trial_csv}"\r\n'
    )

    # Always write thermal parameters- use_thermal flag tells the script whether to act on them
    if use_thermal:
        header += (
            f'use_thermal = 1\r\n' # use_themral will always be 0 or 1
            f'temp_lower = {temp_lower} C\r\n'
            f'temp_upper = {temp_upper} C\r\n'
            f'temp_dwell = {temp_dwell} s\r\n'
            f'ramp_rate = {temp_ramp} V/s\r\n'
        )
    else:
        header += (
            f'use_thermal = 0\r\n' 
            f'temp_lower = 0 C\r\n'
            f'temp_upper = 0 C\r\n'
            f'temp_dwell = 0 s\r\n'
            f'ramp_rate = 0 V/s\r\n'
        )

    if position is not None:
        header += f'position = {position}\r\n'
    header += '\r\n' #uProcess syntax requires an extra newline after the header for proper parsing

    if not os.path.exists(BASE_USQ):
        raise FileNotFoundError(f'Base USQ not found: {BASE_USQ}')

    with open(BASE_USQ, 'r', encoding='ascii', errors='replace') as f:
        base = f.read()

    return (header + base).replace('\n', '\r\n').replace('\x00', '') 

# CSV Analysis 

def extract_flow(csv_file):
    '''
    Read a uProcess output CSV and identify the time and flow columns.

    Looks for columns containing 'Time (s)' and 'SF06'. Falls back to the
    first two numeric columns if those names are not found.

    Parameters:
    - csv_file: path to the CSV file

    Returns:
    A tuple of (time_col_name, flow_col_name, dataframe),
    or (None, None, df) if the expected columns are missing
    '''
    df = pd.read_csv(csv_file, sep=';', skiprows=[0])
    df.columns = df.columns.str.strip()

    time_col = next((c for c in df.columns if 'Time (s)' in c), None)
    flow_col  = next((c for c in df.columns if 'SF06' in c), None)

    if not time_col or not flow_col:
        numeric = df.select_dtypes(include=[np.number])
        if numeric.shape[1] < 2:
            return None, None, df
        time_col, flow_col = numeric.columns[0], numeric.columns[1]

    df[time_col] = pd.to_numeric(df[time_col], errors='coerce')
    df[flow_col]  = pd.to_numeric(df[flow_col],  errors='coerce')
    return time_col, flow_col, df.dropna(subset=[time_col, flow_col])


def compute_steady_mean_from_dispense(df, time_col, flow_col, dispense_time_s, position=None):
    '''
    Compute the steady-state mean flow from the dispense portion of the run data.

    Finds the dispense start time from the valve 2 state column, then averages
    flow over the middle half of the expected dispense window to avoid transients.

    Parameters:
    - df:               DataFrame containing the run data
    - time_col:         name of the time column
    - flow_col:         name of the flow column
    - dispense_time_s:  expected dispense duration (seconds)
    - position:         valve position used to detect when dispensing started

    Returns:
    The steady-state mean flow as a float, or None if it cannot be computed
    '''
    if df is None or len(df) == 0:
        return None

    # Locate the valve state column and find when dispensing started
    t_start   = None
    valve_col = next((c for c in df.columns if 'v2' in c.lower() and 'state' in c.lower()), None)

    if position is not None and valve_col is not None:
        vals_num  = pd.to_numeric(df[valve_col], errors='coerce')
        match_idx = np.where(vals_num == float(position))[0]
        if match_idx.size == 0:
            match_idx = np.where(df[valve_col].astype(str).str.strip() == str(position))[0]
        if match_idx.size > 0:
            try:
                t_start = float(df.iloc[int(match_idx[0])][time_col])
            except Exception:
                pass

    if t_start is None:
        return None

    # Average over the middle half of the dispense window
    mid_start = t_start + dispense_time_s / 4.0
    mid_end   = t_start + 3.0 * dispense_time_s / 4.0
    sample    = df[(df[time_col] >= mid_start) & (df[time_col] <= mid_end)]

    if sample.empty:
        sample = df[(df[time_col] >= t_start) & (df[time_col] <= t_start + dispense_time_s)]
    if sample.empty:
        return None

    return float(np.mean(sample[flow_col]))

# Plotting 

def plot_overlay(df, time_col, flow_col, pressure_col, out_png, title=None):
    '''
    Save a flow-vs-time plot with an optional pressure overlay on a secondary y-axis.

    Parameters:
    - df:           DataFrame with the data to plot
    - time_col:     name of the time column
    - flow_col:     name of the flow column
    - pressure_col: name of the pressure column (can be None)
    - out_png:      file path to save the output image
    - title:        optional plot title

    Returns:
    True if the plot was saved successfully, False otherwise
    '''
    try:
        fig = Figure(figsize=(8, 4))
        ax1 = fig.add_subplot(111)
        ax1.plot(df[time_col], df[flow_col], color='tab:blue', label='Flow (uL/min)')
        ax1.set_xlabel('Time (s)' if isinstance(time_col, str) and 'time' in time_col.lower() else time_col)
        ax1.set_ylabel('Flow (uL/min)', color='tab:blue')
        ax1.tick_params(axis='y', labelcolor='tab:blue')

        if pressure_col and pressure_col in df.columns:
            ax2 = ax1.twinx()
            ax2.plot(df[time_col], df[pressure_col], color='tab:red', label='Pressure (kPa)')
            ax2.set_ylabel('Pressure (kPa)', color='tab:red')
            ax2.tick_params(axis='y', labelcolor='tab:red')

        if title:
            ax1.set_title(title)
        fig.tight_layout()
        fig.savefig(out_png, dpi=150)
        return True
    except Exception:
        return False


def plot_temperature(df, time_col, temp_col, out_png, title=None):
    '''
    Save a temperature-vs-time plot for a single run or combined dataset.

    Parameters:
    - df:       DataFrame with the data to plot
    - time_col: name of the time column
    - temp_col: name of the temperature column
    - out_png:  file path to save the output image
    - title:    optional plot title

    Returns:
    True if the plot was saved successfully, False otherwise
    '''
    try:
        fig = Figure(figsize=(8, 4))
        ax  = fig.add_subplot(111)
        ax.plot(df[time_col], df[temp_col], color='tab:orange', linewidth=2, label='Temperature')
        ax.set_xlabel('Time (s)' if isinstance(time_col, str) and 'time' in time_col.lower() else time_col)
        ax.set_ylabel('Temperature (C)', color='tab:orange')
        ax.tick_params(axis='y', labelcolor='tab:orange')
        ax.grid(True, alpha=0.3)
        if title:
            ax.set_title(title)
        fig.tight_layout()
        fig.savefig(out_png, dpi=150)
        return True
    except Exception:
        return False

